class BitReader:
    def __init__(self, data: bytes):
        self.data = data
        self.bit = 0

    def peek(self, bits: int) -> int:
        value = 0
        bit = self.bit
        for _ in range(bits):
            byte_index = bit >> 3
            value <<= 1
            value |= (self.data[byte_index] >> (7 - (bit & 7))) & 1
            bit += 1
        return value

    def read(self, bits: int) -> int:
        value = self.peek(bits)
        self.bit += bits
        return value

    def skip(self, bits: int) -> None:
        self.bit += bits

    def rewind(self, bits: int) -> None:
        self.bit -= bits


def _crc16_checksum(data: bytes) -> int:
    total = 0
    for byte in data:
        total = ((total << 8) ^ CRC16_TABLE[((total >> 8) ^ byte) & 0xFF]) & 0xFFFF
    return total


def _build_ath_curve(ath_type: int, sample_rate: int) -> tuple[int, ...]:
    if ath_type == 0:
        return tuple(0 for _ in range(HCA_SAMPLES_PER_SUBFRAME))
    if ath_type != 1:
        raise HCAError(f'Unsupported HCA ATH type: {ath_type}')
    curve = [0] * HCA_SAMPLES_PER_SUBFRAME
    acc = 0
    for i in range(HCA_SAMPLES_PER_SUBFRAME):
        acc += sample_rate
        index = acc >> 13
        if index >= 654:
            for j in range(i, HCA_SAMPLES_PER_SUBFRAME):
                curve[j] = 0xFF
            break
        curve[i] = ATH_BASE_CURVE[index]
    return tuple(curve)


def _build_cipher_table(ciph_type: int) -> tuple[int, ...]:
    if ciph_type == 0:
        return tuple(range(256))
    if ciph_type == 1:
        value = 0
        table = [0]
        for _ in range(254):
            value = (value * 13 + 11) & 0xFF
            if value in (0, 0xFF):
                value = (value * 13 + 11) & 0xFF
            table.append(value)
        table.append(0xFF)
        return tuple(table)
    raise HCAError(f'Unsupported HCA cipher type: {ciph_type}')


def _ceil2(a: int, b: int) -> int:
    return (a // b + (1 if a % b else 0)) if b > 0 else 0


def _parse_hca(data: bytes) -> HCAInfo:
    if len(data) < 8:
        raise HCAError('HCA file is too small')
    magic, version, header_size = struct.unpack_from('>IHH', data, 0)
    if (magic & HCA_MASK) != 0x48434100:
        raise HCAError('Invalid HCA header')
    if len(data) < header_size:
        raise HCAError('Incomplete HCA header')
    if _crc16_checksum(data[:header_size]) != 0:
        raise HCAError('Invalid HCA header checksum')
    offset = 8
    fmt_magic, channel_count, sr0, sr1, sr2, block_count, encoder_delay, encoder_padding = struct.unpack_from('>IB3BIHH', data, offset)
    if (fmt_magic & HCA_MASK) != 0x666D7400:
        raise HCAError('Missing HCA fmt chunk')
    sample_rate = (sr0 << 16) | (sr1 << 8) | sr2
    offset += 0x10
    comp_magic = struct.unpack_from('>I', data, offset)[0]
    if (comp_magic & HCA_MASK) == 0x636F6D70:
        (_, block_size, min_resolution, max_resolution, track_count, channel_config, total_band_count, base_band_count, stereo_band_count, bands_per_hfr_group, ms_stereo, _) = struct.unpack_from('>IH10B', data, offset)
        offset += 0x10
    elif (comp_magic & HCA_MASK) == 0x64656300:
        _, block_size, min_resolution, max_resolution, total_band_count, base_band_count, temp, stereo_type = struct.unpack_from('>IH6B', data, offset)
        total_band_count += 1
        base_band_count += 1
        if stereo_type == 0:
            base_band_count = total_band_count
        track_count = temp >> 4
        channel_config = temp & 0x0F
        stereo_band_count = total_band_count - base_band_count
        bands_per_hfr_group = 0
        ms_stereo = 0
        offset += 0x0C
    else:
        raise HCAError('Missing HCA comp/dec chunk')
    if track_count == 0:
        track_count = 1
    if offset + 4 <= len(data) and (struct.unpack_from('>I', data, offset)[0] & HCA_MASK) == 0x76627200:
        offset += 0x08
    if offset + 4 <= len(data) and (struct.unpack_from('>I', data, offset)[0] & HCA_MASK) == 0x61746800:
        _, ath_type = struct.unpack_from('>IH', data, offset)
        offset += 0x06
    else:
        ath_type = 1 if version < HCA_VERSION_V200 else 0
    if offset + 4 <= len(data) and (struct.unpack_from('>I', data, offset)[0] & HCA_MASK) == 0x6C6F6F70:
        _, loop_start_frame, loop_end_frame, loop_start_delay, loop_end_padding = struct.unpack_from('>IIIHH', data, offset)
        loop_enabled = True
        offset += 0x10
    else:
        loop_start_frame = 0
        loop_end_frame = 0
        loop_start_delay = 0
        loop_end_padding = 0
        loop_enabled = False
    if offset + 4 <= len(data) and (struct.unpack_from('>I', data, offset)[0] & HCA_MASK) == 0x63697068:
        _, ciph_type = struct.unpack_from('>IH', data, offset)
        offset += 0x06
    else:
        ciph_type = 0
    if offset + 4 <= len(data) and (struct.unpack_from('>I', data, offset)[0] & HCA_MASK) == 0x72766100:
        offset += 0x08
    if offset + 4 <= len(data) and (struct.unpack_from('>I', data, offset)[0] & HCA_MASK) == 0x636F6D6D:
        _, comment_len = struct.unpack_from('>IB', data, offset)
        offset += 5 + comment_len
    if version <= HCA_VERSION_V200:
        if (min_resolution, max_resolution) != (1, 15):
            raise HCAError('Unsupported HCA resolution range')
    elif min_resolution > max_resolution or max_resolution > 15:
        raise HCAError('Unsupported HCA resolution range')
    hfr_group_count = _ceil2(total_band_count - base_band_count - stereo_band_count, bands_per_hfr_group)
    channels_per_track = channel_count // track_count
    channel_types = [DISCRETE] * channel_count
    if stereo_band_count > 0 and channels_per_track > 1:
        cursor = 0
        for _ in range(track_count):
            if channels_per_track == 2:
                channel_types[cursor:cursor + 2] = [STEREO_PRIMARY, STEREO_SECONDARY]
            elif channels_per_track == 3:
                channel_types[cursor:cursor + 2] = [STEREO_PRIMARY, STEREO_SECONDARY]
            elif channels_per_track == 4:
                channel_types[cursor:cursor + 2] = [STEREO_PRIMARY, STEREO_SECONDARY]
                if channel_config == 0:
                    channel_types[cursor + 2:cursor + 4] = [STEREO_PRIMARY, STEREO_SECONDARY]
            elif channels_per_track == 5:
                channel_types[cursor:cursor + 2] = [STEREO_PRIMARY, STEREO_SECONDARY]
                if channel_config <= 2:
                    channel_types[cursor + 3:cursor + 5] = [STEREO_PRIMARY, STEREO_SECONDARY]
            elif channels_per_track == 6:
                channel_types[cursor:cursor + 2] = [STEREO_PRIMARY, STEREO_SECONDARY]
                channel_types[cursor + 4:cursor + 6] = [STEREO_PRIMARY, STEREO_SECONDARY]
            elif channels_per_track == 7:
                channel_types[cursor:cursor + 2] = [STEREO_PRIMARY, STEREO_SECONDARY]
                channel_types[cursor + 4:cursor + 6] = [STEREO_PRIMARY, STEREO_SECONDARY]
            elif channels_per_track == 8:
                channel_types[cursor:cursor + 2] = [STEREO_PRIMARY, STEREO_SECONDARY]
                channel_types[cursor + 4:cursor + 8] = [STEREO_PRIMARY, STEREO_SECONDARY, STEREO_PRIMARY, STEREO_SECONDARY]
            cursor += channels_per_track
    channels = []
    for channel_type in channel_types:
        coded_count = base_band_count + (stereo_band_count if channel_type != STEREO_SECONDARY else 0)
        channels.append(HCAChannel(channel_type=channel_type, coded_count=coded_count))
    return HCAInfo(
        version=version,
        header_size=header_size,
        sample_rate=sample_rate,
        channel_count=channel_count,
        block_size=block_size,
        block_count=block_count,
        encoder_delay=encoder_delay,
        encoder_padding=encoder_padding,
        min_resolution=min_resolution,
        max_resolution=max_resolution,
        track_count=track_count,
        channel_config=channel_config,
        total_band_count=total_band_count,
        base_band_count=base_band_count,
        stereo_band_count=stereo_band_count,
        bands_per_hfr_group=bands_per_hfr_group,
        ms_stereo=ms_stereo,
        ath_type=ath_type,
        loop_enabled=loop_enabled,
        loop_start_frame=loop_start_frame,
        loop_end_frame=loop_end_frame,
        loop_start_delay=loop_start_delay,
        loop_end_padding=loop_end_padding,
        ciph_type=ciph_type,
        hfr_group_count=hfr_group_count,
        channel_types=channel_types,
        start_band=base_band_count + stereo_band_count,
        channels=channels,
        cipher_table=_build_cipher_table(ciph_type),
        ath_curve=_build_ath_curve(ath_type, sample_rate),
    )


def _unpack_scalefactors(channel: HCAChannel, br: BitReader, hfr_group_count: int, version: int) -> None:
    coded_count = channel.coded_count
    extra_count = 0
    delta_bits = br.read(3)
    if channel.channel_type != STEREO_SECONDARY and hfr_group_count > 0 and version > HCA_VERSION_V200:
        extra_count = hfr_group_count
        coded_count += extra_count
        if coded_count > HCA_SAMPLES_PER_SUBFRAME:
            raise HCAError('Invalid HCA scale factor count')
    if delta_bits >= 6:
        for i in range(coded_count):
            channel.scalefactors[i] = br.read(6)
    elif delta_bits > 0:
        expected_delta = (1 << delta_bits) - 1
        value = br.read(6)
        channel.scalefactors[0] = value
        for i in range(1, coded_count):
            delta = br.read(delta_bits)
            if delta == expected_delta:
                value = br.read(6)
            else:
                value = (value - (expected_delta >> 1) + delta) & 0x3F
            channel.scalefactors[i] = value
    else:
        for i in range(HCA_SAMPLES_PER_SUBFRAME):
            channel.scalefactors[i] = 0
    for i in range(extra_count):
        channel.scalefactors[HCA_SAMPLES_PER_SUBFRAME - 1 - i] = channel.scalefactors[coded_count - i]


def _unpack_intensity(channel: HCAChannel, br: BitReader, hfr_group_count: int, version: int) -> None:
    if channel.channel_type == STEREO_SECONDARY:
        if version <= HCA_VERSION_V200:
            value = br.peek(4)
            channel.intensity[0] = value
            if value < 15:
                br.skip(4)
                for i in range(1, HCA_SUBFRAMES):
                    channel.intensity[i] = br.read(4)
        else:
            value = br.read(4)
            if value < 15:
                delta_bits = br.read(2)
                channel.intensity[0] = value
                if delta_bits == 3:
                    for i in range(1, HCA_SUBFRAMES):
                        channel.intensity[i] = br.read(4)
                else:
                    bmax = (2 << delta_bits) - 1
                    bits = delta_bits + 1
                    for i in range(1, HCA_SUBFRAMES):
                        delta = br.read(bits)
                        if delta == bmax:
                            value = br.read(4)
                        else:
                            value += delta - (bmax >> 1)
                            if value > 15:
                                raise HCAError('Invalid HCA intensity value')
                        channel.intensity[i] = value
            else:
                for i in range(HCA_SUBFRAMES):
                    channel.intensity[i] = 7
    elif version <= HCA_VERSION_V200:
        for i in range(hfr_group_count):
            channel.scalefactors[HCA_SAMPLES_PER_SUBFRAME - hfr_group_count + i] = br.read(6)


def _calculate_resolution(channel: HCAChannel, packed_noise_level: int, ath_curve: tuple[int, ...], min_resolution: int, max_resolution: int) -> None:
    noise_count = 0
    valid_count = 0
    for i in range(channel.coded_count):
        scalefactor = channel.scalefactors[i]
        if scalefactor > 0:
            noise_level = ath_curve[i] + ((packed_noise_level + i) >> 8)
            curve_position = noise_level + 1 - ((5 * scalefactor) >> 1)
            if curve_position < 0:
                resolution = 15
            elif curve_position <= 65:
                resolution = INVERT_TABLE[curve_position]
            else:
                resolution = 0
            if resolution > max_resolution:
                resolution = max_resolution
            elif resolution < min_resolution:
                resolution = min_resolution
            if resolution < 1:
                channel.noises[noise_count] = i
                noise_count += 1
            else:
                channel.noises[HCA_SAMPLES_PER_SUBFRAME - 1 - valid_count] = i
                valid_count += 1
            channel.resolution[i] = resolution
        else:
            channel.resolution[i] = 0
    for i in range(channel.coded_count, HCA_SAMPLES_PER_SUBFRAME):
        channel.resolution[i] = 0
    channel.noise_count = noise_count
    channel.valid_count = valid_count


def _calculate_gain(channel: HCAChannel) -> None:
    for i in range(channel.coded_count):
        channel.gain[i] = DEQUANTIZER_SCALING_TABLE[channel.scalefactors[i]] * DEQUANTIZER_RANGE_TABLE[channel.resolution[i]]


def _dequantize_coefficients(channel: HCAChannel, br: BitReader) -> None:
    for i in range(channel.coded_count):
        resolution = channel.resolution[i]
        bits = MAX_BIT_TABLE[resolution]
        code = br.read(bits)
        if resolution > 7:
            signed_code = (1 - ((code & 1) << 1)) * (code >> 1)
            if signed_code == 0:
                br.rewind(1)
            qc = float(signed_code)
        else:
            index = (resolution << 4) + code
            br.skip(READ_BIT_TABLE[index] - bits)
            qc = READ_VAL_TABLE[index]
        channel.spectra[i] = channel.gain[i] * qc
    for i in range(channel.coded_count, HCA_SAMPLES_PER_SUBFRAME):
        channel.spectra[i] = 0.0


def _reconstruct_noise(channel: HCAChannel, min_resolution: int, ms_stereo: int, random_state: dict[str, int]) -> None:
    if min_resolution > 0 or channel.valid_count <= 0 or channel.noise_count <= 0:
        return
    if ms_stereo and channel.channel_type != STEREO_PRIMARY:
        return
    for i in range(channel.noise_count):
        random_state['state'] = (0x343FD * random_state['state'] + 0x269EC3) & 0x7FFFFFFF
        random_index = HCA_SAMPLES_PER_SUBFRAME - channel.valid_count + (((random_state['state'] & 0x7FFF) * channel.valid_count) >> 15)
        noise_index = channel.noises[i]
        valid_index = channel.noises[random_index]
        sc_index = channel.scalefactors[noise_index] - channel.scalefactors[valid_index] + 62
        if sc_index < 0:
            sc_index = 0
        channel.spectra[noise_index] = SCALE_CONVERSION_TABLE[sc_index] * channel.spectra[valid_index]


def _reconstruct_high_frequency(channel: HCAChannel, info: HCAInfo) -> None:
    if info.bands_per_hfr_group == 0 or channel.channel_type == STEREO_SECONDARY:
        return
    highband = info.start_band
    lowband = info.start_band - 1
    hfr_scales_offset = HCA_SAMPLES_PER_SUBFRAME - info.hfr_group_count
    group_limit = info.hfr_group_count if info.version <= HCA_VERSION_V200 else info.hfr_group_count >> 1
    for group in range(info.hfr_group_count):
        lowband_sub = 1 if group < group_limit else 0
        for _ in range(info.bands_per_hfr_group):
            if highband >= info.total_band_count or lowband < 0:
                break
            sc_index = channel.scalefactors[hfr_scales_offset + group] - channel.scalefactors[lowband] + 63
            if sc_index < 0:
                sc_index = 0
            channel.spectra[highband] = SCALE_CONVERSION_TABLE[sc_index] * channel.spectra[lowband]
            highband += 1
            lowband -= lowband_sub
    if highband > 0:
        channel.spectra[highband - 1] = 0.0


def _apply_intensity_stereo(left: HCAChannel, right: HCAChannel, subframe: int, base_band_count: int, total_band_count: int) -> None:
    if left.channel_type != STEREO_PRIMARY:
        return
    ratio_l = INTENSITY_RATIO_TABLE[right.intensity[subframe]]
    ratio_r = 2.0 - ratio_l
    for band in range(base_band_count, total_band_count):
        coef = left.spectra[band]
        left.spectra[band] = coef * ratio_l
        right.spectra[band] = coef * ratio_r


def _apply_ms_stereo(left: HCAChannel, right: HCAChannel, ms_stereo: int, base_band_count: int, total_band_count: int) -> None:
    if not ms_stereo or left.channel_type != STEREO_PRIMARY:
        return
    ratio = 0.70710676908493
    for band in range(base_band_count, total_band_count):
        coef_l = (left.spectra[band] + right.spectra[band]) * ratio
        coef_r = (left.spectra[band] - right.spectra[band]) * ratio
        left.spectra[band] = coef_l
        right.spectra[band] = coef_r


def _imdct_transform(channel: HCAChannel) -> list[float]:
    size = HCA_SAMPLES_PER_SUBFRAME
    half = size // 2
    temp1 = channel.spectra
    temp2 = channel.temp
    count1 = 1
    count2 = half
    for _ in range(HCA_MDCT_BITS):
        src = 0
        for group in range(count1):
            d1 = group * count2 * 2
            d2 = d1 + count2
            for _ in range(count2):
                a = temp1[src]
                b = temp1[src + 1]
                temp2[d1] = a + b
                temp2[d2] = a - b
                src += 2
                d1 += 1
                d2 += 1
        temp1, temp2 = temp2, temp1
        count1 <<= 1
        count2 >>= 1
    count1 = half
    count2 = 1
    temp1 = channel.temp
    temp2 = channel.spectra
    for stage in range(HCA_MDCT_BITS):
        sin_table = SIN_TABLES[stage]
        cos_table = COS_TABLES[stage]
        table_index = 0
        d1 = 0
        d2 = count2 * 2 - 1
        s1 = 0
        s2 = count2
        for _ in range(count1):
            for _ in range(count2):
                a = temp1[s1]
                b = temp1[s2]
                sin_v = sin_table[table_index]
                cos_v = cos_table[table_index]
                temp2[d1] = a * sin_v - b * cos_v
                temp2[d2] = a * cos_v + b * sin_v
                table_index += 1
                d1 += 1
                d2 -= 1
                s1 += 1
                s2 += 1
            s1 += count2
            s2 += count2
            d1 += count2
            d2 += count2 * 3
        temp1, temp2 = temp2, temp1
        count1 >>= 1
        count2 <<= 1
    dct = channel.spectra
    prev = channel.imdct_previous
    wave_out = [0.0] * size
    for i in range(half):
        wave_out[i] = IMDCT_WINDOW[i] * dct[i + half] + prev[i]
        wave_out[i + half] = IMDCT_WINDOW[i + half] * dct[size - 1 - i] - prev[i + half]
        prev[i] = IMDCT_WINDOW[size - 1 - i] * dct[half - i - 1]
        prev[i + half] = IMDCT_WINDOW[half - i - 1] * dct[i]
    return wave_out


def _decode_frame(frame: bytes, info: HCAInfo, random_state: dict[str, int]) -> list[int]:
    if len(frame) < info.block_size:
        raise HCAError('Incomplete HCA frame')
    frame = frame[:info.block_size]
    if _crc16_checksum(frame) != 0:
        raise HCAError('Invalid HCA frame checksum')
    decrypted = bytes(info.cipher_table[b] for b in frame)
    br = BitReader(decrypted)
    if br.read(16) != 0xFFFF:
        raise HCAError('Invalid HCA frame sync')
    packed_noise_level = (br.read(9) << 8) - br.read(7)
    for channel in info.channels:
        _unpack_scalefactors(channel, br, info.hfr_group_count, info.version)
        _unpack_intensity(channel, br, info.hfr_group_count, info.version)
        _calculate_resolution(channel, packed_noise_level, info.ath_curve, info.min_resolution, info.max_resolution)
        _calculate_gain(channel)
    pcm = []
    for subframe in range(HCA_SUBFRAMES):
        for channel in info.channels:
            _dequantize_coefficients(channel, br)
        for channel in info.channels:
            _reconstruct_noise(channel, info.min_resolution, info.ms_stereo, random_state)
            _reconstruct_high_frequency(channel, info)
        if info.stereo_band_count > 0:
            for i in range(info.channel_count - 1):
                left = info.channels[i]
                right = info.channels[i + 1]
                _apply_intensity_stereo(left, right, subframe, info.base_band_count, info.total_band_count)
                _apply_ms_stereo(left, right, info.ms_stereo, info.base_band_count, info.total_band_count)
        waves = [_imdct_transform(channel) for channel in info.channels]
        for sample_index in range(HCA_SAMPLES_PER_SUBFRAME):
            for channel_index in range(info.channel_count):
                sample = waves[channel_index][sample_index]
                if sample > 1.0:
                    sample = 1.0
                elif sample < -1.0:
                    sample = -1.0
                value = int(sample * 32768.0)
                if value > 32767:
                    value = 32767
                elif value < -32768:
                    value = -32768
                pcm.append(value)
    return pcm


def decode_hca_to_wav_bytes(data: bytes) -> bytes:
    info = _parse_hca(data)
    total_samples = info.block_count * HCA_SAMPLES_PER_FRAME - info.encoder_delay - info.encoder_padding
    if total_samples < 0:
        raise HCAError('Invalid HCA sample count')
    raw = io.BytesIO()
    wav = wave.open(raw, 'wb')
    wav.setnchannels(info.channel_count)
    wav.setsampwidth(2)
    wav.setframerate(info.sample_rate)
    random_state = {'state': HCA_DEFAULT_RANDOM}
    skip_samples = info.encoder_delay
    remaining_samples = total_samples
    for block_index in range(info.block_count):
        frame_offset = info.header_size + block_index * info.block_size
        pcm = _decode_frame(data[frame_offset:frame_offset + info.block_size], info, random_state)
        frame_samples = HCA_SAMPLES_PER_FRAME
        start = min(skip_samples, frame_samples)
        skip_samples -= start
        keep = min(remaining_samples, frame_samples - start)
        if keep <= 0:
            continue
        remaining_samples -= keep
        clipped = pcm[start * info.channel_count:(start + keep) * info.channel_count]
        wav.writeframes(struct.pack('<' + 'h' * len(clipped), *clipped))
        if remaining_samples <= 0:
            break
    wav.close()
    return raw.getvalue()


def decode_hca_file(
    input_path: str | os.PathLike[str],
    output_path: str | os.PathLike[str],
) -> None:
    src_path = Path(input_path)
    dst_path = Path(output_path)
    dst_path.write_bytes(decode_hca_to_wav_bytes(src_path.read_bytes()))
